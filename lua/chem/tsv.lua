-- Which cells of a TSV buffer hold a chemical structure, for the smarts
-- injection in queries/tsv/injections.scm. A column qualifies when its header
-- names a line notation (chem/notation.lua) or when it has been marked by hand.
-- The mark says "this column holds a structure" and names no language: SMILES
-- and SMARTS are both read by the one smarts parser.
--
-- Columns are counted in tabs and read off the buffer's lines rather than off
-- the tree, because the tsv grammar drops an empty cell instead of noding it:
-- `x<TAB><TAB>y` is two fields, so `y` would count as column 2 and every column
-- right of a missing value would shift left. Rows come from the tree, which is
-- what it is good for.
local notation = require "chem/notation"
local map = require "utils/keymap"
local util = require "utils/init"

local M = {}

--- @type table<integer, { tick: integer, lnum: integer|nil, names: string[] }>
local headers = {}

--- True when column `index` has been marked by hand. The `vim.NIL` test is what
--- `vim.b` needs from every reader of a list it may have padded holes into —
--- `vim.NIL` is truthy.
--- @param buf integer
--- @param index integer
--- @return boolean
local function is_marked(buf, index)
    local column = (vim.b[buf].chem_columns or {})[index]
    return column ~= nil and column ~= vim.NIL and column ~= false
end

--- One line of a buffer.
--- @param buf integer
--- @param lnum integer 0-based
--- @return string
local function line(buf, lnum)
    return vim.api.nvim_buf_get_lines(buf, lnum, lnum + 1, true)[1]
end

--- The 1-based column index a byte column falls in. A cell holding a tab would
--- break this, and the format has none — the same assumption ftplugin/tsv.lua
--- declares.
--- @param prefix string the line up to the position
--- @return integer
local function column_index(prefix)
    local _, tabs = prefix:gsub("\t", "")
    return tabs + 1
end

--- True when a line is a comment. The grammar has no notion of one, so
--- `# generated by rdkit` is an ordinary row, and the character comes from
--- 'commentstring' — where the ftplugin takes it from too.
--- @param buf integer
--- @param text string
--- @return boolean
local function is_comment(buf, text)
    local char = vim.bo[buf].commentstring:sub(1, 1)
    return char ~= "" and text:match("^[\t ]*" .. vim.pesc(char)) ~= nil
end

--- The first two lines of a document that are not comments: a header candidate
--- and the line that decides whether it is one. Taken from the tree's rows
--- rather than by scanning lines, so a long comment block costs no more than
--- the parse already did.
--- @param document TSNode
--- @param buf integer
--- @return integer|nil first 0-based line number
--- @return integer|nil second
local function leading_lines(document, buf)
    local first
    for i = 0, document:named_child_count() - 1 do
        local lnum = assert(document:named_child(i)):start()
        if not is_comment(buf, line(buf, lnum)) then
            if first then return first, lnum end
            first = lnum
        end
    end
    return first, nil
end

--- The line the columns are named on, or nil for a document with no header to
--- trust. A first row of numbers is data rather than names (`.bed` resolves to
--- filetype tsv and is headerless), and a header with fewer fields than its
--- first data row — R's `write.table` omits the rowname column's name —
--- offsets every index.
--- @param document TSNode
--- @param buf integer
--- @return integer|nil lnum 0-based line number
local function header_line(document, buf)
    local first, second = leading_lines(document, buf)
    if not first or not second then return end
    local names = vim.split(line(buf, first), "\t", { plain = true })
    if #names ~= #vim.split(line(buf, second), "\t", { plain = true }) then return end
    for _, name in ipairs(names) do
        if tonumber(name) then return end
    end
    return first
end

--- The header of a buffer as the predicate needs it, remembered until the text
--- changes. Recomputing it per cell doubles the cost of a parse: the predicate
--- runs for every text cell of the parsed range, and finding the header walks
--- rows and splits two lines. Only 'commentstring' can change it without
--- changing the text, and only into a header a comment row was hiding.
--- @param document TSNode
--- @param buf integer
--- @return integer|nil lnum 0-based line number of the header, nil for none
--- @return string[] names the column names, empty without a header
local function header(document, buf)
    local tick = vim.api.nvim_buf_get_changedtick(buf)
    local cached = headers[buf]
    if not cached or cached.tick ~= tick then
        local lnum = header_line(document, buf)
        cached = {
            tick = tick,
            lnum = lnum,
            names = lnum and vim.split(line(buf, lnum), "\t", { plain = true }) or {},
        }
        headers[buf] = cached
    end
    return cached.lnum, cached.names
end

--- True when the ftplugin is hiding column `index` — which is to say the column
--- is in hiding mode, whether or not any of its cells was long enough to have
--- text taken out of the buffer. Injecting into a truncated cell would parse the
--- truncation as the structure. The read is explicit rather than through the
--- ftplugin, whose accessors are file-locals: `vim.b.tsv_hidden` holds the
--- hidden columns only, so `vim.b` pads the holes with the truthy `vim.NIL`.
--- @param buf integer
--- @param index integer
--- @return boolean
local function is_hidden(buf, index)
    local column = (vim.b[buf].tsv_hidden or {})[index]
    return column ~= nil and column ~= vim.NIL
end

--- Query predicate `(#chem-column? @cap)` — true when @cap is a TSV cell whose
--- column holds a chemical structure. @cap is the `(text)` child of a `field`.
--- @param match table<integer, TSNode[]>
--- @param _ integer pattern index (unused)
--- @param source integer|string buffer or string
--- @param pred any[]
--- @return boolean
function M.is_chem_column(match, _, source, pred)
    -- The header, the hand marks and the hidden columns are all buffer state.
    if type(source) ~= "number" then return false end
    local node = (match[pred[2]] or {})[1]
    if not node then return false end
    -- A `""` inside a quoted cell stands for one quote, and unquoting is a
    -- range over buffer text, which cannot undouble it. Such a cell would
    -- inject with the artefact in it, and no structure holds a quote anyway.
    if vim.treesitter.get_node_text(node, source):find('""') then return false end

    local lnum, col = node:start()
    local text = line(source, lnum)
    if is_comment(source, text) then return false end
    -- The root of the tree the cell was parsed from is the `document`.
    local header_lnum, names = header(node:tree():root(), source)
    if lnum == header_lnum then return false end

    local index = column_index(text:sub(1, col))
    if is_hidden(source, index) then return false end
    if is_marked(source, index) then return true end
    return names[index] ~= nil and notation.of(names[index]) ~= nil
end

--- Mark the column under the cursor as holding chemical structures, or unmark
--- it. For a header the notation set does not name; a column it does name stays
--- chemical either way.
function M.toggle_column()
    local lnum, col = util.get_cursor()
    local index = column_index(line(0, lnum):sub(1, col))
    local columns = vim.b.chem_columns or {}
    columns[index] = not is_marked(0, index)
    vim.b.chem_columns = columns
    -- The injection query only runs again on a reparse, and the mark changes
    -- nothing about the text that would prompt one.
    assert(vim.treesitter.get_parser(0)):invalidate(true)
end

--- Bind the mark keymap in every TSV buffer, and forget a buffer's header when
--- it goes. The predicate itself is registered in plugin/treesitter.lua, with
--- every other query handler.
function M.setup()
    local group = vim.api.nvim_create_augroup("chem.tsv", { clear = true })
    vim.api.nvim_create_autocmd("FileType", {
        pattern = "tsv",
        group = group,
        callback = function(args)
            map.map("n", "<localleader>c", M.toggle_column,
                { buffer = args.buf, desc = "Toggle chemical column" })
        end,
    })
    vim.api.nvim_create_autocmd("BufWipeout", {
        group = group,
        callback = function(args) headers[args.buf] = nil end,
    })
end

return M
