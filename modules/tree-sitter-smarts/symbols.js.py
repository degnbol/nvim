#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["rdkit"]
# ///
"""Emit the alphabets RDKit's SMILES and SMARTS parsers actually accept.

Probed rather than read off the periodic table: Z=0's symbol is `*`, which would
collide with the wildcard token, and the SMARTS parser accepts a strict subset of
the elements. Bare (outside a bracket atom) and bracketed alphabets are disjoint
sets, since the same two characters lex as one atom or two depending on bracket
depth.
"""

import json
import string
from pathlib import Path

from rdkit import Chem, rdBase

# Every rejected probe logs a parse error otherwise.
rdBase.DisableLog("rdApp.*")

PERIODIC_TABLE = Chem.GetPeriodicTable()


def atom_query(smarts: str) -> Chem.Mol | None:
    """Parse as SMARTS.

    Args:
        smarts: a SMARTS string.

    Returns:
        The molecule, or None if it did not parse.
    """
    return Chem.MolFromSmarts(smarts)


def lexes_as(smiles: str, z: int, aromatic: bool) -> bool:
    """Whether both parsers read a string as the single atom it names.

    A two-letter sequence outside brackets is two atoms (`Sn` is sulfur +
    nitrogen), and `[Nh]` is nitrogen + implicit-H count to the SMARTS parser
    while it is nihonium to the SMILES parser. Both fail the atomic-number
    check, which is how such symbols stay out of the emitted sets. Where the
    SMARTS parser rejects a symbol outright (`Mc`, `Ts`, `Og`) the SMILES
    reading stands alone.

    Args:
        smiles: the candidate spelling, bare or bracketed.
        z: atomic number the spelling should name.
        aromatic: whether the spelling should name an aromatic atom.

    Returns:
        True if the spelling lexes as exactly that one atom.
    """

    def one_atom(mol: Chem.Mol | None) -> bool:
        if mol is None or mol.GetNumAtoms() != 1:
            return False
        atom = mol.GetAtomWithIdx(0)
        return atom.GetAtomicNum() == z and atom.GetIsAromatic() == aromatic

    query = atom_query(smiles)
    if query is not None:
        return one_atom(query)
    return one_atom(Chem.MolFromSmiles(smiles, sanitize=False))


def element_alphabet(bracketed: bool, aromatic: bool) -> list[str]:
    """The element symbols one parse context accepts.

    Args:
        bracketed: probe inside `[ ]` rather than bare.
        aromatic: probe the lowercased symbol as an aromatic atom.

    Returns:
        Accepted symbols, in atomic-number order.
    """
    accepted = []
    for z in range(1, 119):
        symbol = PERIODIC_TABLE.GetElementSymbol(z)
        if aromatic:
            symbol = symbol.lower()
        spelling = f"[{symbol}]" if bracketed else symbol
        if lexes_as(spelling, z, aromatic):
            accepted.append(symbol)
    return accepted


def property_primitives() -> dict[str, bool]:
    """The non-element atom primitives, mapped to whether a digit is required.

    Single characters that name a property (degree, ring membership, valence,
    hybridisation) rather than an element. Element symbols, the `H` count and
    the `A`/`a` wildcards are excluded: they are separate grammar tokens.

    Returns:
        Primitive character → True if it only parses with a trailing digit.
    """
    elements = {PERIODIC_TABLE.GetElementSymbol(z) for z in range(1, 119)}
    aromatics = set(element_alphabet(bracketed=True, aromatic=True))
    reserved = {s for s in elements | aromatics if len(s) == 1} | {"A", "a", "H"}

    probed = {}
    for char in string.ascii_letters + "^":
        if char in reserved:
            continue
        bare = atom_query(f"[#6&{char}]") is not None
        with_digit = atom_query(f"[#6&{char}1]") is not None
        if bare or with_digit:
            probed[char] = not bare
    return probed


sets = {
    "bareAliphatic": element_alphabet(bracketed=False, aromatic=False),
    "bareAromatic": element_alphabet(bracketed=False, aromatic=True),
    "bracketElement": element_alphabet(bracketed=True, aromatic=False),
    "bracketAromatic": element_alphabet(bracketed=True, aromatic=True),
}
probed = property_primitives()
sets["propertyPrimitives"] = [c for c, needs_digit in probed.items() if not needs_digit]
sets["propertyPrimitivesWithDigit"] = [c for c, needs_digit in probed.items() if needs_digit]

lines = [f"// Generated by {Path(__file__).name} from rdkit {rdBase.rdkitVersion}.", ""]
lines += [f"const {name} = {json.dumps(members)};" for name, members in sets.items()]
lines += ["", f"module.exports = {{ {', '.join(sets)} }};", ""]
Path(__file__).with_suffix("").write_text("\n".join(lines))
